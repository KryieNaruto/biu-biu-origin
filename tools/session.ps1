# Pre-rendered strings: storing the code point arrays and joining them on every
# lookup is fragile (array unrolling / legacy parser behaviour turns the join
# into a space separated number list). Build the string ONCE, here, and have
# T() do a plain hashtable hit.
$script:TEXTS = @{}
foreach ($k in $script:TEXTDEF.Keys) {
    $cps = $script:TEXTDEF[$k]
    $sb = New-Object System.Text.StringBuilder
    for ($i = 0; $i -lt $cps.Length; $i++) { [void]$sb.Append([char]([int]$cps[$i])) }
    $script:TEXTS[$k] = $sb.ToString()
}

# --- output: write UTF-8 bytes directly, bypassing the console code page ----
$script:Utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$script:StdOut = [Console]::OpenStandardOutput()

function Out-Line([string]$text) {
    if ($null -eq $text) { $text = '' }
    $bytes = $script:Utf8NoBom.GetBytes($text + "`r`n")
    $script:StdOut.Write($bytes, 0, $bytes.Length)
    $script:StdOut.Flush()
}

function Out-Blank() { Out-Line '' }

