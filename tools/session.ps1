function Get-StateLabel($wt) {
    if ($wt.prunable) { return (T 'state-prunable') }
    if ($wt.locked) { return (T 'state-locked') }
    if (Test-Dirty $wt.path) { return (T 'state-dirty') }
    return (T 'state-clean')
}

function Measure-Width([string]$s) {
    $w = 0
    foreach ($ch in $s.ToCharArray()) {
        if ([int]$ch -gt 127) { $w += 2 } else { $w += 1 }
    }
    return $w
}

function Pad-Display([string]$s, [int]$width) {
    $disp = 0
    foreach ($ch in $s.ToCharArray()) {
        if ([int]$ch -gt 127) { $disp += 2 } else { $disp += 1 }
    }
    $pad = $width - $disp
    if ($pad -lt 0) { $pad = 0 }
    return ($s + (' ' * $pad))
}

function Show-List {
    Show-Header (T 'list-hdr')
    Out-Blank

    $wts = Get-Worktrees
    $rows = New-Object System.Collections.ArrayList
    $sessionCount = 0
    $mergedCount = 0

    foreach ($w in $wts) {
        if ($w.bare) { continue }
        $onSessionBranch = [bool]$w.branch.StartsWith('session/')
        $inContainer = [bool](([string]$w.path).StartsWith($script:WorktreeRoot + [char]'\'))
        $isSession = [bool]($onSessionBranch -or $inContainer)
        if ($isSession) {
            if ($onSessionBranch) {
                $nameText = $w.branch.Substring(8)
            } elseif ($inContainer) {
                $nameText = [string]$w.path.Substring($script:WorktreeRoot.Length + 1)
            } else {
                $nameText = $w.path
            }
            $sessionCount++
        }
        $branchText = $w.branch
        if ($w.detached) { $branchText = '(detached)' }
        $state = [string](Get-StateLabel $w)
        if ($isSession) {
            if (Test-MergedInto $w.branch $Base $ProjectRoot) {
                $state = $state + ' / ' + (T 'state-merged')
                $mergedCount++
            } else {
                $state = $state + ' / ' + (T 'state-unmerged')
            }
        } else {
            $nameText = (T 'list-main-row')
        }
        $row = New-Object PSObject -Property @{
            name    = [string]$nameText
            branch  = [string]$branchText
            path    = [string]$w.path
            state   = $state
            head    = [string](Get-Subject $w.path)
            session = $isSession
        }
        [void]$rows.Add($row)
    }

    if (@($rows).Count -eq 0) {
        Out-Line (T 'list-none')
    } else {
        $colNames = @('name', 'branch', 'path', 'state', 'head')
        $hdrCols = New-Object System.Collections.ArrayList
        foreach ($h in ((T 'wt-header') -split '\|')) { [void]$hdrCols.Add([string]$h) }
        if ($hdrCols.Count -ne 5) { $hdrCols = @('name', 'branch', 'path', 'state', 'head') }

        # columns 0..3 are padded; the head/subject column is last and not padded
        $widths = New-Object 'int[]' 5
        for ($k = 0; $k -lt 4; $k++) {
            $widths[$k] = [int](Measure-Width ([string]$hdrCols[$k]))
        }
        foreach ($row in $rows) {
            for ($k = 0; $k -lt 4; $k++) {
                $w0 = [int](Measure-Width ([string]$row.($colNames[$k])))
                if ($w0 -gt $widths[$k]) { $widths[$k] = $w0 }
            }
        }
        $line = ''
        for ($k = 0; $k -lt 4; $k++) { $line += (Pad-Display ([string]$hdrCols[$k]) $widths[$k]) + '  ' }
        $line += [string]$hdrCols[4]
        Out-Line $line
        Out-Line ('-' * 110)
        foreach ($row in $rows) {
            $line = ''
            for ($k = 0; $k -lt 4; $k++) { $line += (Pad-Display ([string]$row.($colNames[$k])) $widths[$k]) + '  ' }
            $line += [string]$row.head
            Out-Line $line
        }
    }

    Out-Blank
    Out-Line ((T 'list-total') -f $sessionCount, $mergedCount)
    if ($mergedCount -gt 0) { Hint (T 'list-hint-stop') }
    Show-Footer
    return $script:ExitCode
}

# ============================================================================
function Invoke-Start {
    Show-Header ((T 'title') + ' / start ' + $Name)
    Out-Blank

    $existing = Find-SessionWorktree $Name
    if ($null -ne $existing) {
        Fail ((T 'start-already') -f $Name) 4
        Hint ((T 'start-already-hint') -f $Name)
        Show-Footer
        return $script:ExitCode
    }
    $branch = Get-SessionBranch $Name
    if (Test-RefExists $branch $ProjectRoot) {
        Fail ((T 'start-branch-exists') -f $Name) 4
        Hint ((T 'start-branch-hint') -f $Name)
        Show-Footer
        return $script:ExitCode
    }
    $wtPath = Get-WorktreePath $Name
    if (Test-Path -LiteralPath $wtPath) {
        Fail ((T 'start-path-exists') -f $wtPath) 4
        Hint (T 'start-path-hint')
        Show-Footer
        return $script:ExitCode
    }
    if (-not (Test-RefExists $Base $ProjectRoot)) {
        $nb = Invoke-Git @('branch', '--format=%(refname:short)') $ProjectRoot
        $names = [string]$nb.text
        Fail ((T 'start-base-missing') -f $Base) 4
        Hint ((T 'start-base-hint') -f $names)
        Show-Footer
        return $script:ExitCode
    }

    Assert-CleanState

    $r = Invoke-Git @('worktree', 'add', $wtPath, '-b', $branch, $Base) $ProjectRoot
    if ($r.code -ne 0) {
        Fail ((T 'err-git-failed') -f $r.code, ('worktree add ' + $wtPath)) 5
        Hint $r.text
        Show-Footer
        return $script:ExitCode
    }

    Out-Line ((T 'start-ok') -f $Name)
    Out-Line ((T 'start-path') -f $wtPath)
    Out-Line ((T 'start-branch') -f $Name, $Base)
    Out-Blank
    Out-Line (T 'start-next')
    Out-Line ((T 'start-cd') -f $wtPath)
    Out-Blank
    Out-Line (T 'start-remind')
    Show-Footer
    return $script:ExitCode
}

# ============================================================================
# 7. subcommand: status
# ============================================================================
function Invoke-Status {
    Show-Header ((T 'status-title') -f $Name)
    Out-Blank

    $wt = Find-SessionWorktree $Name
    $branch = Get-SessionBranch $Name
    if ($null -eq $wt) {
        Fail ((T 'err-wt-missing') -f $Name) 4
        Out-Blank
        Out-Line ((T 'label-branch') + ' : ' + $branch)
        Out-Line ((T 'label-main') + ' : ' + $Base)
        Show-Footer
        return $script:ExitCode
    }

    # Ask about the BRANCH, not the worktree: a worktree sitting on an old
    # detached HEAD (e.g. left behind by a mid-finish rebase) would otherwise
    # report the branch as merged when it is not.
    $merged = Test-MergedInto $branch $Base $ProjectRoot
    $porcelain = Get-Porcelain $wt.path
    $changeCount = 0
    if ($null -ne $porcelain) { $changeCount = $porcelain.Count }

    Out-KV (T 'label-worktree') ($wt.path) 14
    Out-KV (T 'label-branch') ($branch) 14
    Out-KV (T 'label-head') ((Get-Subject $wt.path)) 14
    Out-KV (T 'label-main') ($Base + '  ' + (Get-Subject $ProjectRoot)) 14
    if ($merged) {
        Out-KV (T 'label-merged') (T 'yes') 14
    } else {
        Out-KV (T 'label-merged') (T 'no') 14
    }
    $ab = Get-AheadBehind $branch $Base $ProjectRoot
    if ($ab) {
        $abParts = @($ab -split '\|')
        # ahead/behind counts COMMITTED history only; with uncommitted work in
        # the tree an "ahead 0" line reads as a contradiction, so say so
        $abLabel = T 'label-ahead'
        if ($changeCount -gt 0) { $abLabel = T 'label-ahead-committed' }
        Out-KV $abLabel (TF 'ahead-fmt' @($abParts[0], $abParts[1], $Base, $branch)) 14
        if ($changeCount -gt 0) { Hint (T 'ahead-footnote') }
    }
    if ($changeCount -eq 0) {
        Out-KV (T 'label-clean') (T 'state-clean') 14
        Out-KV (T 'label-changes') (T 'label-none') 14
    } else {
        Out-KV (T 'label-clean') ((T 'state-dirty') + '  (' + $changeCount + ')') 14
        Out-KV (T 'label-changes') '' 14
        foreach ($l in $porcelain) { Out-Line ('    ' + $l) }
    }

    Out-Blank
    if ($changeCount -gt 0) {
        # uncommitted work is not part of the branch yet: say so before the
        # "already merged" line, otherwise the two read as contradictory
        Out-Line ('WARN   ' + ((T 'status-dirty') -f $Name))
        Hint ((T 'finish-commit-hint') -f $Name)
        Out-Blank
    }
    if ($merged) {
        # "merged" only makes sense for COMMITTED work; when the worktree is
        # still dirty, that work is not on the branch yet -- do not hand out
        # the cleanup hint or the user will stop a session with unsaved work
        if ($changeCount -eq 0) {
            Out-Line ((T 'status-merged') -f $Name, $Base)
        } else {
            Out-Line ((T 'status-merged-dirty') -f $Name, $Base)
        }
    } else {
        Out-Line ((T 'status-not-merged') -f $Name, $Base)
    }

    # guard: the main worktree should not carry uncommitted work (rule 8 s.3)
    if (Test-Dirty $ProjectRoot) {
        Out-Blank
        Out-Line ('WARN   ' + ((T 'commit-dirty-main') -f $ProjectRoot))
        Hint (T 'commit-main-hint')
    }
    Show-Footer
    return $script:ExitCode
}

function Invoke-Commit {
    Show-Header ((T 'title') + ' / commit ' + $Name)
    Out-Blank

    if ($Message.Length -eq 0) {
        Fail (T 'err-commit-msg') 1
        Show-Footer
        return $script:ExitCode
    }
    $wt = Find-SessionWorktree $Name
    if ($null -eq $wt) {
        Fail ((T 'err-wt-missing') -f $Name) 4
        Show-Footer
        return $script:ExitCode
    }
    if (Test-Dirty $ProjectRoot) {
        Out-Line ('WARN   ' + ((T 'commit-dirty-main') -f $ProjectRoot))
        Hint (T 'commit-main-hint')
        Out-Blank
    }

    $porcelain = Get-Porcelain $wt.path
    $n = 0
    if ($null -ne $porcelain) { $n = $porcelain.Count }
    if ($n -eq 0) {
        Out-Line ((T 'commit-dry'))
        Show-Footer
        return $script:ExitCode
    }

    # Rule 8 / M4: "git add -A" is what let one session sweep another session's
    # half-finished edits of a shared document into its own commit. It cannot be
    # simply dropped (a normal session needs its new files staged too), so keep
    # the behaviour but name the shared files that are about to ride along and
    # point at the all-staged case: when everything is already staged, commit
    # them as they are instead of widening the index.
    $alreadyStaged = $false
    $null = & $script:GitExe -C $wt.path diff --cached --quiet 2>&1
    if ($LASTEXITCODE -eq 1) { $alreadyStaged = $true }
    $protected = Get-ProtectedPaths (Get-ModifiedPaths $wt.path)
    if (-not $alreadyStaged -and @($protected).Count -gt 0) {
        Out-Line ('WARN   ' + (T 'commit-add-all'))
        foreach ($p in $protected) { Hint ('    ' + $p) }
        Out-Blank
    }

    $r = Invoke-Git @('add', '-A') $wt.path
    if ($r.code -ne 0) {
        Fail ((T 'err-git-failed') -f $r.code, 'add -A') 5
        Hint $r.text
        Show-Footer
        return $script:ExitCode
    }
    $r = Invoke-Git @('commit', '-m', $Message) $wt.path
    if ($r.code -ne 0) {
        Fail ((T 'err-git-failed') -f $r.code, ('commit -m "' + $Message + '"')) 5
        Hint $r.text
        Show-Footer
        return $script:ExitCode
    }
    Out-Line ((T 'commit-ok') -f $n, $Name)
    Out-Line ((T 'commit-ok-msg') -f (Get-Subject $wt.path))
    Out-Blank
    Out-Line ((T 'commit-next-finish') -f $Name)
    Show-Footer
    return $script:ExitCode
}

# ============================================================================
# 9. subcommand: finish
# ============================================================================
function Invoke-Finish {
    Show-Header ((T 'title') + ' / finish ' + $Name)
    Out-Blank

    $wt = Find-SessionWorktree $Name
    if ($null -eq $wt) {
        Fail ((T 'err-wt-missing') -f $Name) 4
        Show-Footer
        return $script:ExitCode
    }
    $branch = Get-SessionBranch $Name
    $main = Get-MainWorktree
    if ($null -eq $main) {
        Fail (T 'err-repo-missing-hint') 3
        Show-Footer
        return $script:ExitCode
    }

    # ---- step 1: session worktree must be clean ---------------------------
    Out-Line (T 'finish-step-commit')
    $porcelain = Get-Porcelain $wt.path
    if (@($porcelain).Count -gt 0) {
        Fail ((T 'finish-has-changes') -f $Name) 6
        foreach ($l in $porcelain) { Out-Line ('    ' + $l) }
        Hint ((T 'finish-commit-hint') -f $Name)
        Show-Footer
        return $script:ExitCode
    }

    # ---- step 2: main worktree must be there, then switch to Base ---------
    Out-Line ((T 'finish-step-checkout') -f $Base)
    $curBranch = Get-CurrentBranch $main.path
    if ($curBranch -ne $Base) {
        $r = Invoke-Git @('checkout', $Base) $main.path
        if ($r.code -ne 0) {
            Fail ((T 'finish-switch-fail') -f $Base) 7
            Hint $r.text
            Hint (T 'finish-switch-hint')
            Show-Footer
            return $script:ExitCode
        }
    } else {
        # already on Base, but make sure the working tree is not stale mid-merge
        if (Test-Path -LiteralPath (Join-Path $main.path '.git\MERGE_HEAD')) {
            Fail ((T 'finish-switch-fail') -f $Base) 7
            Hint (T 'finish-switch-hint')
            Show-Footer
            return $script:ExitCode
        }
    }

    # ---- step 3: rebase the session branch onto the latest Base -----------
    Out-Line ((T 'finish-step-rebase') -f $Name, $Base)
    # -a --amend --no-edit: a rebase stops on a commit whose diff was already
    # applied by the merged side; resolving the conflict and committing it as
    # an empty commit would then block the rebase. Amending is the documented
    # way out (see the printed guide).
    $r = Invoke-Git @('rebase', $Base) $wt.path
    if ($r.code -ne 0) {
        Fail ((T 'finish-rebase-fail') -f $Name, $Base) 7
        Out-Blank
        Out-Line (T 'finish-rebase-guide')
        Out-Line ((T 'finish-rebase-g1') -f $wt.path)
        Out-Line (T 'finish-rebase-g2')
        Out-Line (T 'finish-rebase-g3')
        Out-Line (T 'finish-rebase-g5')
        Out-Line ((T 'finish-rebase-g4') -f $Name)
        Out-Blank
        Hint (T 'finish-rebase-abort')
        Show-Footer
        return $script:ExitCode
    }

    # ---- step 4: merge --no-ff back into Base -----------------------------
    Out-Line ((T 'finish-step-merge') -f $Name, $Base)
    # git merge refuses when a file it must write still has TRACKED local
    # modifications in the target worktree ("Your local changes to the
    # following files would be overwritten by merge"). Detect exactly that
    # set up front instead of letting git abort with a bare "merge failed",
    # and print the offending paths so the session owner can act.
    $target = Invoke-Git @('log', '--name-only', '--pretty=format:', ($Base + '..' + $branch)) $ProjectRoot
    $willOverwrite = New-Object System.Collections.ArrayList
    if ($target.code -eq 0) {
        # PowerShell flattens ArrayList on return in ways that depend on the
        # call site ("@(f)" still yields a one-element array wrapping the list
        # when f ends with "return , $list"). Flatten explicitly instead of
        # reasoning about it.
        $dirty = New-Object System.Collections.ArrayList
        foreach ($d in (Get-ModifiedPaths $main.path)) {
            foreach ($x in @($d)) { [void]$dirty.Add([string]$x) }
        }
        $dirtySet = @{}
        foreach ($d in $dirty) { $dirtySet[[string]$d] = $true }
        $seen = @{}
        foreach ($f in ([string]$target.text -split "`r?`n")) {
            $t = $f.Trim()
            if ($t.Length -eq 0) { continue }
            if ($seen.ContainsKey($t)) { continue }
            $seen[$t] = $true
            if ($dirtySet.ContainsKey($t)) { [void]$willOverwrite.Add($t) }
        }
    }
    if (@($willOverwrite).Count -gt 0) {
        Fail ((T 'err-target-files') -f (@($willOverwrite) -join ', ')) 8
        foreach ($f in $willOverwrite) { Hint ('    ' + $f) }
        Hint (T 'err-target-files-hint')
        Show-Footer
        return $script:ExitCode
    }

    $r = Invoke-Git @('merge', '--no-ff', '-m', ('merge ' + $branch + ' into ' + $Base), $branch) $main.path
    if ($r.code -ne 0) {
        $mr = Invoke-Git @('merge', '--abort') $main.path
        Fail (T 'finish-merge-fail') 8
        # The old code swallowed git's own diagnostic here, which is why the
        # failure looked unexplained; print it (both the merge and the abort).
        Hint ((T 'finish-merge-reason'))
        foreach ($l in (([string]$r.text -split "`r?`n"))) {
            if ($l.Trim().Length -gt 0) { Hint ('    ' + $l.Trim()) }
        }
        if ($mr.code -ne 0 -and [string]$mr.text -match '\S') {
            foreach ($l in (([string]$mr.text -split "`r?`n"))) {
                if ($l.Trim().Length -gt 0) { Hint ('    abort: ' + $l.Trim()) }
            }
        }
        Hint (T 'finish-clean-hint')
        Hint ((T 'finish-merge-hint') -f $Name, $Base)
        Show-Footer
        return $script:ExitCode
    }

    Out-Blank
    Out-Line ((T 'finish-ok') -f $Base)
    Out-Line ((T 'finish-merged-log') -f (Get-Subject $main.path))
    if ($NoDelete) {
        Out-Line ((T 'finish-keep') -f $wt.path)
    }
    Out-Blank
    Out-Line (T 'finish-next-clean')
    Out-Line (T 'finish-c1')
    Out-Line (T 'finish-c2')
    Out-Line ((T 'finish-c3') -f $Name)
    Show-Footer
    return $script:ExitCode
}

# ============================================================================
# 10. subcommand: stop
# ============================================================================
function Invoke-Stop {
    Show-Header ((T 'title') + ' / stop ' + $Name)
    Out-Blank

    $wt = Find-SessionWorktree $Name
    if ($null -eq $wt) {
        # worktree gone: maybe only the branch is left behind
        $branch = Get-SessionBranch $Name
        if (Test-RefExists $branch $ProjectRoot) {
            Out-Line ((T 'err-wt-missing') -f $Name)
            $merged = Test-MergedInto $branch $Base $ProjectRoot
            if (-not $merged) {
                Fail ((T 'stop-no-merge') -f $Name, $Base) 9
                Hint ((T 'stop-no-merge-hint') -f $Name)
            } else {
                Out-Line ((T 'stop-step-branch') -f $Name)
                $r = Invoke-Git @('branch', '-d', $branch) $ProjectRoot
                if ($r.code -ne 0) {
                    Fail (T 'stop-branch-fail') 10
                    Hint $r.text
                } else {
                    Out-Line ((T 'stop-ok') -f $Name)
                }
            }
        } else {
            Fail ((T 'err-wt-missing') -f $Name) 4
        }
        Show-Footer
        return $script:ExitCode
    }

    $branch = Get-SessionBranch $Name

    # ---- guard 1: unmerged branch => refuse (no -D, ever) -----------------
    if (-not (Test-MergedInto $branch $Base $ProjectRoot)) {
        Fail ((T 'stop-no-merge') -f $Name, $Base) 9
        Hint ((T 'stop-no-merge-hint') -f $Name)
        Show-Footer
        return $script:ExitCode
    }
    # ---- guard 2: dirty worktree => refuse --------------------------------
    if (Test-Dirty $wt.path) {
        Fail ((T 'stop-dirty') -f $Name) 9
        Hint (T 'stop-dirty-hint')
        Show-Footer
        return $script:ExitCode
    }

    Out-Line (T 'stop-step-remove')
    $r = Invoke-Git @('worktree', 'remove', $wt.path) $ProjectRoot
    if ($r.code -ne 0) {
        Fail ((T 'stop-remove-fail') -f $wt.path) 10
        Hint $r.text
        Hint (T 'stop-remove-hint')
        Show-Footer
        return $script:ExitCode
    }

    Out-Line ((T 'stop-step-branch') -f $Name)
    $r = Invoke-Git @('branch', '-d', $branch) $ProjectRoot
    if ($r.code -ne 0) {
        Fail (T 'stop-branch-fail') 10
        Hint $r.text
        Show-Footer
        return $script:ExitCode
    }

    Out-Line ((T 'stop-ok') -f $Name)
    Hint ((T 'stop-merged-note') -f $Base)

    if (-not (Test-Path -LiteralPath $script:WorktreeRoot)) {
        Out-Blank
    } else {
        $rest = @(Get-ChildItem -LiteralPath $script:WorktreeRoot -Force -ErrorAction SilentlyContinue)
        if (@($rest).Count -eq 0) {
            Out-Blank
            Out-Line (T 'list-none')
        }
    }
    Show-Footer
    return $script:ExitCode
}

