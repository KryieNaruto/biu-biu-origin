# returns $true when it is safe to continue
function Test-Common([switch]$NeedName) {
    if (-not $script:GitExe) {
        Fail (T 'err-git-missing') 3
        return $false
    }
    if (-not (Test-Path -LiteralPath $ProjectRoot)) {
        Fail (T 'err-repo-missing-hint') 3
        return $false
    }
    if (-not (Test-Path -LiteralPath (Join-Path $ProjectRoot '.git'))) {
        Fail (TF 'err-no-repo' @($ProjectRoot)) 2
        Hint (T 'hint-init')
        Hint (T 'hint-plan')
        return $false
    }
    $repoRoot = Resolve-RepoRoot
    if (-not $repoRoot) {
        Fail (TF 'err-no-repo' @($ProjectRoot)) 2
        Hint (T 'hint-init')
        Hint (T 'hint-plan')
        return $false
    }
    if ($NeedName) {
        if ($Name.Length -eq 0) {
            Fail (TF 'err-need-name' @($Action)) 1
            return $false
        }
        if (-not (Test-SessionName $Name)) {
            Fail (TF 'err-name-invalid' @($Name)) 1
            Hint (T 'err-name-rule')
            return $false
        }
    }
    return $true
}

