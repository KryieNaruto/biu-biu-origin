# 11. main dispatch
# ============================================================================
$Action = $Action.Trim().ToLowerInvariant()

try { $host.UI.RawUI.WindowTitle = T 'title' } catch { }

switch ($Action) {
    '' {
        Show-Usage
        $script:ExitCode = 1
    }
    'list' {
        if (Test-Common) { $script:ExitCode = Show-List }
    }
    'start' {
        if (Test-Common -NeedName) { $script:ExitCode = Invoke-Start }
    }
    'status' {
        if (Test-Common -NeedName) { $script:ExitCode = Invoke-Status }
    }
    'commit' {
        if (Test-Common -NeedName) { $script:ExitCode = Invoke-Commit }
    }
    'finish' {
        if (Test-Common -NeedName) { $script:ExitCode = Invoke-Finish }
    }
    'stop' {
        if (Test-Common -NeedName) { $script:ExitCode = Invoke-Stop }
    }
    'help' {
        Show-Usage
        $script:ExitCode = 0
    }
    default {
        Fail ((T 'err-action-unknown') -f $Action) 1
        Out-Blank
        Show-Usage
    }
}

exit $script:ExitCode
