# ============================================================================
# tools/session.ps1 - BiuBiuOrigin parallel-session worktree manager (rule 8)
# ============================================================================
# *** DO NOT "OPTIMIZE" THIS FILE INTO PLAIN-TEXT CHINESE ***
#   Same rule as tools/env.ps1: this script is intentionally pure-ASCII source.
#   All Chinese output lives in the $script:TEXTDEF table below as key -> text
#   pairs, and $script:TEXTS is derived from it at startup as Unicode code
#   points. Reason: PowerShell 5.1 reads a BOM-less .ps1 with the ANSI code page
#   (GBK here); raw UTF-8 Chinese gets mangled at parse time, and some byte
#   pairs even swallow the following newline, which surfaces as
#   "Unexpected token '}'". Keep the source ASCII-only. Always.
#
# WHAT THIS SCRIPT IS FOR
#   Rule 8 (docs/rules/08-parallel-sessions.md): the project is developed by
#   several parallel sessions. Every session gets its own git worktree on its
#   own branch (session/<name>), placed OUTSIDE the project root, and merges
#   back into main when done.
#
#     <repo parent>/
#       biu-biu-origin/           <- main worktree (branch main), owns .git
#       .worktrees/<name>/        <- one session worktree per session
#
#   worktree (not clone, not branch switching): shares the single .git object
#   store (zero copy), gives every session an isolated checkout, and never
#   disturbs the main tree's Godot editor / .godot import cache.
#
# SUBCOMMANDS
#   .\tools\session.ps1 list
#   .\tools\session.ps1 start   -Name <name> [-Base main]
#   .\tools\session.ps1 status  -Name <name>
#   .\tools\session.ps1 commit  -Name <name> -Message "<text>"
#   .\tools\session.ps1 finish  -Name <name> [-NoDelete]
#   .\tools\session.ps1 stop    -Name <name>
#
# BEHAVIOUR NOTES
#   - Not a git repository yet? The script prints "run git init first" and
#     exits 0. It never throws because the repo is missing.
#   - Destructive operations are refused, never forced: stop refuses when the
#     branch is unmerged or the worktree is dirty (rule 8 section 2.6), and no
#     -Force switch exists on purpose.
#   - finish = commit check -> rebase session branch onto main -> merge --no-ff.
#     On rebase conflict it stops and prints resolution steps; neither branch
#     is modified by the script at that point.
#   - Local only. No push, no remote.
#
# Runtime: Windows PowerShell 5.1 (no PS7-only syntax: no ?? / ?: / &&)
# ============================================================================

