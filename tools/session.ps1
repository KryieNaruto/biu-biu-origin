# 4. guards: name validation, git presence, repo presence
# ============================================================================
function Test-SessionName([string]$n) {
    if ($n.Length -lt 1) { return $false }
    if ($n.Length -gt 24) { return $false }
    if ($n -notmatch '^[a-z0-9][a-z0-9-]*$') { return $false }
    if ($n.EndsWith('-')) { return $false }
    if ($n -eq 'main' -or $n -eq 'master' -or $n -eq 'head') { return $false }
    return $true
}

